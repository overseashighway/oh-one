-- OH ONE Phase 1 schema; import only into the dedicated empty OH ONE database.
SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS offices (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(150) NOT NULL,
 code VARCHAR(30) NOT NULL UNIQUE,
 country_code CHAR(2) NOT NULL,
 city VARCHAR(100) NULL,
 is_active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS leads (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 office_id BIGINT UNSIGNED NOT NULL,
 full_name VARCHAR(200) NOT NULL,
 email VARCHAR(255) NULL,
 phone VARCHAR(50) NULL,
 service_interest VARCHAR(60) NULL,
 status VARCHAR(40) NOT NULL DEFAULT 'new',
 source VARCHAR(80) NULL,
 notes TEXT NULL,
 created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_leads_office_created (office_id, created_at),
 INDEX idx_leads_status (status),
 CONSTRAINT fk_leads_office FOREIGN KEY (office_id) REFERENCES offices(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
